  const SUPPORTED = ['zh-CN', 'zh-TW', 'en-US', 'ja-JP', 'ko-KR', 'fr-FR', 'ru-RU'];

  let language = 'zh-CN';
  let scheduled = false;

  function normalize(value) {
    return String(value == null ? '' : value).replace(/\s+/g, ' ').trim();
  }

  const PHRASES = Object.keys(EN)
    .filter((key) => key.length > 1)
    .sort((a, b) => b.length - a.length);

  function targetFor(chinese) {
    const english = EN[chinese] || chinese;
    if (language === 'zh-CN') return chinese;
    if (language === 'en-US') return english;
    const table = LOCALES[language];
    return (table && table[english]) || english;
  }

  function translateText(value) {
    const text = String(value);
    const trimmed = normalize(text);
    if (!trimmed || language === 'zh-CN') return text;
    const exact = targetFor(trimmed);
    if (exact !== trimmed) return text.replace(trimmed, exact);
    // Do not machine-compose paragraphs or announcements. Only short UI labels
    // and labels joined with " · " get phrase-by-phrase replacement.
    if (trimmed.length > 48 || /[，。！？；：]/.test(trimmed)) return text;
    // Safe fallback for composed labels such as "主页 · 开发者版本".
    // Only known UI phrases are replaced; user data and unknown text stay intact.
    let out = text;
    for (const key of PHRASES) {
      if (out.includes(key)) out = out.split(key).join(targetFor(key));
    }
    return out;
  }

  function translateElement(root) {
    if (!root || language === 'zh-CN') return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        if (parent.closest('script, style, textarea, code, pre, [data-i18n-skip]')) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
      const next = translateText(node.nodeValue);
      if (next !== node.nodeValue) node.nodeValue = next;
    });
    if (root.querySelectorAll) {
      root.querySelectorAll('[title]:not([data-i18n-skip]), [placeholder]:not([data-i18n-skip]), [aria-label]:not([data-i18n-skip])').forEach((el) => {
        ['title', 'placeholder', 'aria-label'].forEach((attr) => {
          if (!el.hasAttribute(attr)) return;
          const next = translateText(el.getAttribute(attr));
          if (next !== el.getAttribute(attr)) el.setAttribute(attr, next);
        });
      });
    }
  }

  function apply() {
    if (language === 'zh-CN') return;
    translateElement(document.body);
  }

  function schedule() {
    if (scheduled) return;
    scheduled = true;
    requestAnimationFrame(() => {
      scheduled = false;
      apply();
    });
  }

  function setLanguage(value) {
    language = SUPPORTED.includes(value) ? value : 'zh-CN';
    document.documentElement.lang = language;
    if (language !== 'zh-CN') {
      apply();
      schedule();
    }
  }

  window.EMCL_I18N = { setLanguage, apply, t: (key) => (language === 'en-US' ? (EN[key] || key) : key) };
  window.addEventListener('DOMContentLoaded', () => {
    new MutationObserver(schedule).observe(document.body, { childList: true, subtree: true });
  });
